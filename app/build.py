"""
build.py — Sprint Capacity Planner · joins the JavaScript sources into the one shipped file.

What ships to Confluence (PRD File Structure):
    scp-macro.html    pasted into the HTML macro on the planning page
    scp-planner.css   attached to the planning page
    scp-planner.js    attached to the planning page; MADE BY THIS SCRIPT

The sources below stay separate for editing and testing. Each is a self-contained
block that shares only window.SCP, so joining them in load order runs exactly as
loading them one by one did. Edit the sources, never scp-planner.js, then run:

    python build.py           write scp-planner.js
    python build.py --check   exit 1 if scp-planner.js does not match the sources

The output has no date or time in it, so the same sources always give the same file
(tests/check_build.py relies on that).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = "scp-planner.js"

# Load order: calculations first, the app last (it starts everything).
SOURCES = [
    "scp-calc.js",
    "scp-jira.js",
    "scp-store.js",
    "scp-tab-config.js",
    "scp-tab-tickets.js",
    "scp-tab-resources.js",
    "scp-tab-capacity.js",
    "scp-tab-calendar.js",
    "scp-publish.js",
    "scp-app.js",
]

HEADER = """/*
 * scp-planner.js — Sprint Capacity Planner · all planner code in one file
 *
 * GENERATED by build.py from the source files listed below. Do not edit this
 * file: edit the sources and run "python build.py" again.
 *
 * Sources, in load order:
{files}
 */
"""


def build():
    """The text of scp-planner.js, built from the sources."""
    parts = [HEADER.format(files="\n".join(" *   " + name for name in SOURCES))]
    for name in SOURCES:
        with open(os.path.join(HERE, name), encoding="utf-8") as f:
            text = f.read().rstrip() + "\n"
        parts.append("\n/* ==================== " + name + " ==================== */\n\n" + text)
    return "".join(parts)


def main():
    text = build()
    out = os.path.join(HERE, OUT)
    if "--check" in sys.argv:
        current = open(out, encoding="utf-8").read() if os.path.exists(out) else ""
        if current != text:
            print(OUT + " does not match the sources: run python build.py")
            return 1
        print(OUT + " matches the sources")
        return 0
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d files, %d bytes)" % (OUT, len(SOURCES), len(text.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
